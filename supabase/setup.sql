-- 答えの表記ゆれをそろえる（全角半角・カタカナ→ひらがな・空白や記号を除く）
create or replace function public.nazo_norm(t text)
returns text language sql immutable as $$
    select regexp_replace(
        translate(lower(normalize(coalesce(t, ''), NFKC)),
            'ァアィイゥウェエォオカガキギクグケゲコゴサザシジスズセゼソゾタダチヂッツヅテデトドナニヌネノハバパヒビピフブプヘベペホボポマミムメモャヤュユョヨラリルレロヮワヰヱヲンヴヵヶ',
            'ぁあぃいぅうぇえぉおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねのはばぱひびぴふぶぷへべぺほぼぽまみむめもゃやゅゆょよらりるれろゎわゐゑをんゔゕゖ'),
        '[[:space:]・、。,.!！?？「」『』()（）-]', '', 'g');
$$;

create or replace function public.nazo_check_team(p_team int, p_code text)
returns boolean language sql stable security definer set search_path = public as $$
    select exists (select 1 from nazo_teams where id = p_team and passcode = p_code);
$$;

-- チーム一覧（名前だけ）
create or replace function public.nazo_list_teams()
returns table (id int, name text)
language sql stable security definer set search_path = public as $$
    select id, name from nazo_teams order by id;
$$;

-- チームの今の状態：解いた問題・見えている点・開いている書類・クリアしたか
create or replace function public.nazo_state(p_team int, p_code text)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
    solved text[];
    groups text[] := array['act1'];
    result jsonb;
begin
    if not nazo_check_team(p_team, p_code) then
        raise exception 'チームの合言葉がちがいます';
    end if;

    select coalesce(array_agg(puzzle_id), '{}') into solved from nazo_solves where team_id = p_team;

    if not exists (select 1 from nazo_puzzles where act = 1 and kind = 'sheet' and id <> all(solved)) then
        groups := groups || 'act1final'::text; end if;
    if '1-final' = any(solved) then groups := groups || 'act2'::text; end if;
    if '1-final' = any(solved)
       and not exists (select 1 from nazo_puzzles where act = 2 and kind = 'sheet' and id <> all(solved)) then
        groups := groups || 'act2final'::text; end if;
    if '2-final' = any(solved) then groups := groups || 'act3'::text; end if;
    if '2-final' = any(solved)
       and not exists (select 1 from nazo_puzzles where act = 3 and kind = 'sheet' and id <> all(solved)) then
        groups := groups || 'act3final'::text; end if;
    if '3-final' = any(solved) then groups := groups || 'act4'::text; end if;

    select jsonb_build_object(
        'team', (select jsonb_build_object('id', id, 'name', name) from nazo_teams where id = p_team),
        'solved', to_jsonb(solved),
        'puzzles', (select jsonb_agg(jsonb_build_object('id', id, 'act', act, 'kind', kind) order by act, kind desc, id) from nazo_puzzles),
        'points', coalesce((
            select jsonb_agg(jsonb_build_array(pt.idx, pt.lat, pt.lng) order by pt.idx)
            from nazo_points pt
            where exists (select 1 from nazo_puzzles pz where pz.id = any(solved) and pt.idx = any(pz.points))
        ), '[]'::jsonb),
        'total_points', (select count(*) from nazo_points),
        'pages', (select jsonb_object_agg(grp, slug) from nazo_pages where grp = any(groups)),
        'cleared', (select min(created_at) from nazo_spots where team_id = p_team and is_treasure)
    ) into result;
    return result;
end;
$$;

-- 答えを判定する
create or replace function public.nazo_answer(p_team int, p_code text, p_puzzle text, p_answer text)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
    st jsonb;
    pz nazo_puzzles;
    ok boolean;
    open_groups jsonb;
    grp text;
begin
    st := nazo_state(p_team, p_code);
    select * into pz from nazo_puzzles where id = p_puzzle;
    if pz.id is null then
        return jsonb_build_object('status', 'unknown');
    end if;
    grp := 'act' || pz.act || case when pz.kind = 'final' then 'final' else '' end;
    if not (st -> 'pages') ? grp then
        return jsonb_build_object('status', 'locked');
    end if;
    if (st -> 'solved') ? p_puzzle then
        return jsonb_build_object('status', 'already');
    end if;

    ok := nazo_norm(p_answer) = any(pz.answers);
    insert into nazo_attempts (team_id, puzzle_id, answer, correct) values (p_team, p_puzzle, left(p_answer, 100), ok);
    if not ok then
        return jsonb_build_object('status', 'wrong');
    end if;

    insert into nazo_solves (team_id, puzzle_id) values (p_team, p_puzzle) on conflict do nothing;
    return jsonb_build_object('status', 'correct', 'new_points', cardinality(pz.points), 'state', nazo_state(p_team, p_code));
end;
$$;

-- 地点追加：合言葉が正しいときだけ登録できる。くちばしの先の近くなら宝箱
create or replace function public.nazo_add_spot(p_team int, p_code text, p_name text, p_category text,
    p_note text, p_lat double precision, p_lng double precision, p_password text)
returns jsonb language plpgsql volatile security definer set search_path = public as $$
declare
    tip jsonb;
    radius double precision;
    dist double precision;
    treasure boolean;
begin
    if not nazo_check_team(p_team, p_code) then
        raise exception 'チームの合言葉がちがいます';
    end if;
    insert into nazo_attempts (team_id, puzzle_id, answer, correct)
    values (p_team, 'spot', left(coalesce(p_password, ''), 100),
            exists (select 1 from nazo_settings s, jsonb_array_elements_text(s.value::jsonb) a
                    where s.key = 'password' and a = nazo_norm(p_password)));
    if not exists (select 1 from nazo_settings s, jsonb_array_elements_text(s.value::jsonb) a
                   where s.key = 'password' and a = nazo_norm(p_password)) then
        return jsonb_build_object('status', 'bad_password');
    end if;

    select value::jsonb into tip from nazo_settings where key = 'tip';
    select value::double precision into radius from nazo_settings where key = 'radius_m';
    -- 近い2点の距離（メートル）
    dist := 6371000 * 2 * asin(sqrt(
        power(sin(radians((p_lat - (tip ->> 0)::float8) / 2)), 2) +
        cos(radians(p_lat)) * cos(radians((tip ->> 0)::float8)) *
        power(sin(radians((p_lng - (tip ->> 1)::float8) / 2)), 2)));
    treasure := dist <= radius;

    insert into nazo_spots (team_id, name, category, note, lat, lng, is_treasure)
    values (p_team, left(coalesce(nullif(trim(p_name), ''), '名前のない地点'), 60), left(p_category, 20),
            left(p_note, 200), p_lat, p_lng, treasure);

    return jsonb_build_object('status', case when treasure then 'treasure' else 'added' end,
                              'distance_m', round(dist));
end;
$$;

