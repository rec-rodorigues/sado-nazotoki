create table if not exists public.nazo_teams (
    id int primary key,
    name text not null,
    passcode text not null
);

create table if not exists public.nazo_puzzles (
    id text primary key,
    act int not null,
    kind text not null check (kind in ('sheet', 'final')),
    answers text[] not null,
    points int[] not null default '{}'
);

create table if not exists public.nazo_points (
    idx int primary key,
    lat double precision not null,
    lng double precision not null
);

create table if not exists public.nazo_pages (
    grp text primary key,
    slug text not null
);

create table if not exists public.nazo_settings (
    key text primary key,
    value text not null
);

-- 正解の記録（誰でも閲覧できる。順位表に使う）
create table if not exists public.nazo_solves (
    team_id int not null references public.nazo_teams(id) on delete cascade,
    puzzle_id text not null references public.nazo_puzzles(id) on delete cascade,
    solved_at timestamptz not null default now(),
    primary key (team_id, puzzle_id)
);

-- 回答の記録（運営の確認用。ブラウザからは読めない）
create table if not exists public.nazo_attempts (
    id bigint generated by default as identity primary key,
    team_id int,
    puzzle_id text,
    answer text,
    correct boolean,
    created_at timestamptz not null default now()
);

-- 地点追加（チームが登録したスポット。誰でも閲覧できる）
create table if not exists public.nazo_spots (
    id bigint generated by default as identity primary key,
    team_id int not null references public.nazo_teams(id) on delete cascade,
    name text not null,
    category text,
    note text,
    lat double precision not null,
    lng double precision not null,
    is_treasure boolean not null default false,
    created_at timestamptz not null default now()
);

